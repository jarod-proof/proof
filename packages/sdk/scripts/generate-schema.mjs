// Generates src/schema.gen.ts (the operation types of the SDK) from the committed API contract.
// Run with `pnpm --filter @proof/sdk generate` after `apps/api/openapi.json` changes. The
// schema.test.ts in src re-runs generateSchema in memory and fails when the committed file is stale.
import { readFile, writeFile } from "node:fs/promises"
import { pathToFileURL } from "node:url"
import openapiTS, { astToString } from "openapi-typescript"

export const OPENAPI_PATH = new URL("../../../apps/api/openapi.json", import.meta.url)
export const SCHEMA_PATH = new URL("../src/schema.gen.ts", import.meta.url)

const HEADER =
  "// Generated by scripts/generate-schema.mjs from apps/api/openapi.json. Do not edit by hand.\n// biome-ignore-all format: generated output is kept byte-for-byte as the generator writes it\n"

/** The TypeScript source for the given OpenAPI document (already parsed). */
export async function generateSchema(spec) {
  const ast = await openapiTS(spec)
  return `${HEADER}${astToString(ast)}\n`
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const spec = JSON.parse(await readFile(OPENAPI_PATH, "utf8"))
  await writeFile(SCHEMA_PATH, await generateSchema(spec))
  console.log(`wrote ${SCHEMA_PATH.pathname}`)
}
